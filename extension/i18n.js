let lang = "zh";

export function resolveLang(setting) {
  if (setting === "zh" || setting === "zht" || setting === "en") return setting;
  const nav = (navigator.language || "").toLowerCase();
  if (/^zh-(tw|hk|mo|hant)/.test(nav)) return "zht";
  return nav.startsWith("zh") ? "zh" : "en";
}
export function setLang(l) {
  lang = l;
  document.documentElement.lang = { zh: "zh-CN", zht: "zh-Hant", en: "en" }[l] || "en";
}
export function getLang() { return lang; }

export function t(key, vars) {
  let s = (STRINGS[lang] && STRINGS[lang][key]) ?? STRINGS.zh[key] ?? key;
  if (vars) for (const k in vars) s = s.split(`{${k}}`).join(vars[k]);
  return s;
}

// data-i18n / data-i18n-placeholder / data-i18n-title / data-i18n-aria
export function applyStatic(root = document) {
  root.querySelectorAll("[data-i18n]").forEach((el) => { el.textContent = t(el.dataset.i18n); });
  root.querySelectorAll("[data-i18n-placeholder]").forEach((el) => { el.placeholder = t(el.dataset.i18nPlaceholder); });
  root.querySelectorAll("[data-i18n-title]").forEach((el) => { el.title = t(el.dataset.i18nTitle); el.setAttribute("aria-label", t(el.dataset.i18nTitle)); });
}
